#!/usr/bin/env python3
"""Rename source files (git mv) and update every reference to them.

    py -3.14 tools/rename_file.py --dry-run          # plan from config/US/file_renames.tsv, write nothing
    py -3.14 tools/rename_file.py                    # apply it
    py -3.14 tools/rename_file.py --plan other.tsv   # another plan (same columns)
    py -3.14 tools/rename_file.py src/semantic/a.c src/semantic/b.c --reason "..."   # one file; also
                                                     # appends the row to config/US/file_renames.tsv

The plan is a TSV with the columns old_path, new_path, reason (repository-relative, forward slashes).
Rows whose old file is gone and whose new file exists count as already applied: they are not moved
again, but their references are still updated, so a second run finishes an interrupted one.

What is updated, in every git-tracked text file except the exclusions below:
  - the full path (`src/semantic/game_code1.c` -> `src/semantic/weapon_bullets.c`), which covers
    BUILD_MANIFEST.json units[].source, config/semantic/selection-template.json (unit keys, their
    "source" fields and functions[].source), reference/semantic/*.json and the docs;
  - the bare file name (`game_code1.c`, `movie_grid.hpp`), e.g. #include lines, docs and comments;
  - the bare stem (`game_code1`, `lib_r14e`) in prose, except stems that look like symbol names
    (func_<VA>, sub_<VA>), which stay because the docs use them as old function names.
  A name only matches as a whole token: no letter, digit, `_`, `$`, `.`, `/` or `-` before it, no
  letter, digit or `_` after it (so game_code1 does not touch game_code10, and work/match/<stem>-...
  directories in the template stay as they are). All rows are replaced in one pass (longest match
  first), so a new name is never renamed again by another row.
Files are read and written as bytes (UTF-8, BOM kept), so CRLF and LF line endings are unchanged.

When the contents of a compiled source change (a comment or an #include naming another file), its
source_sha256 in BUILD_MANIFEST.json and the selection template is updated if it was current.

Not edited: config/US/names.tsv (the evidence column may keep old file names), ida_names.tsv,
ida_funcs.tsv, the plan TSV itself, docs/PORT_RENAMES.md, the generated "Renamed files" table in
docs/CODE_MAP.md (between the renamed-files markers; rewritten from the plan instead),
reference/ida/, reference/m2c/ (raw decompiler output with its own func_<VA>.c files),
reference/semantic/tool-snapshots/, this tool, tools/port_rename_notes.py, LAST_*.json (rewritten by
the next build) and PACKAGE.json (regenerated with tools/make_package.py at the end; --no-package
skips that).

Refused (nothing is written): an old file that does not exist (and is not already applied), a new path
that exists, two rows with the same old or new path, a new file whose stem equals the stem of another
file in src/semantic (match_unit work directories and data_audit look units up by stem), a row whose
new path is another row's old path (chains), a path outside the repository, a changed extension.
"""
import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLAN = ROOT / 'config/US/file_renames.tsv'
CODE_MAP = ROOT / 'docs/CODE_MAP.md'
BEGIN = '<!-- renamed-files:begin (generated by tools/rename_file.py from config/US/file_renames.tsv) -->'
END = '<!-- renamed-files:end -->'
EXCLUDE_FILES = {'config/US/names.tsv', 'config/US/ida_names.tsv', 'config/US/ida_funcs.tsv',
                 'docs/PORT_RENAMES.md', 'tools/rename_file.py', 'tools/port_rename_notes.py',
                 'PACKAGE.json', 'LAST_BUILD.json', 'LAST_SOURCE_BUILD.json', 'LAST_RELOC_BUILD.json'}
EXCLUDE_DIRS = ('reference/ida/', 'reference/m2c/', 'reference/semantic/tool-snapshots/')
TEXT_EXT = {'.c', '.cpp', '.h', '.hpp', '.s', '.inc', '.py', '.md', '.json', '.tsv', '.txt', '.cmd', '.ld'}
HASHED = (ROOT / 'BUILD_MANIFEST.json', ROOT / 'config/semantic/selection-template.json')
SYMBOL_STEM = re.compile(r'^(?:func|sub)_[0-9A-Fa-f]{8}$')
LEFT = r'(?<![\w$./-])'
RIGHT = r'(?![\w])'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def git(*args):
    proc = subprocess.run(['git', *args], cwd=ROOT, capture_output=True, text=True, encoding='utf-8')
    if proc.returncode:
        raise SystemExit('rename_file: git %s failed: %s' % (' '.join(args), proc.stderr.strip()))
    return proc.stdout


def read_plan(path):
    rows = []
    for n, line in enumerate(Path(path).read_text(encoding='utf-8').splitlines(), 1):
        if not line.strip() or line.startswith('#') or (n == 1 and line.startswith('old_path')):
            continue
        cols = line.split('\t')
        if len(cols) < 2:
            raise SystemExit('rename_file: %s:%d: expected old_path<TAB>new_path<TAB>reason' % (path, n))
        rows.append(dict(old=cols[0].strip(), new=cols[1].strip(), reason=(cols[2].strip() if len(cols) > 2 else '')))
    return rows


def stem(p):
    return Path(p).stem


def check(rows):
    """Return (problems, rows annotated with state 'todo' or 'applied')."""
    problems = []
    olds = [r['old'] for r in rows]
    news = [r['new'] for r in rows]
    for name, items in (('old', olds), ('new', news)):
        dup = sorted({x for x in items if items.count(x) > 1})
        if dup:
            problems.append('duplicate %s paths: %s' % (name, ', '.join(dup)))
    chained = sorted(set(olds) & set(news))
    if chained:
        problems.append('a new path is another row\'s old path (chain): ' + ', '.join(chained))
    moving = set(olds)
    existing = {}
    for p in (ROOT / 'src/semantic').rglob('*'):
        if p.is_file():
            rel = p.relative_to(ROOT).as_posix()
            existing.setdefault(p.stem, []).append(rel)
    new_stems = [stem(n) for n in news if n.startswith('src/')]
    for s in sorted({x for x in new_stems if new_stems.count(x) > 1}):
        problems.append('two new files share the stem %s' % s)
    for r in rows:
        for key in ('old', 'new'):
            p = r[key]
            if p.startswith('/') or '..' in p.split('/') or '\\' in p or ':' in p:
                problems.append('%s: not a repository-relative path' % p)
        if Path(r['old']).suffix != Path(r['new']).suffix:
            problems.append('%s -> %s: extension changes' % (r['old'], r['new']))
        old_ok, new_ok = (ROOT / r['old']).is_file(), (ROOT / r['new']).exists()
        if old_ok and not new_ok:
            r['state'] = 'todo'
        elif not old_ok and new_ok:
            r['state'] = 'applied'
        elif old_ok and new_ok:
            problems.append('%s: new path already exists (collision)' % r['new'])
        else:
            problems.append('%s: old file does not exist' % r['old'])
        if r['new'].startswith('src/'):
            others = [x for x in existing.get(stem(r['new']), []) if x != r['new'] and x not in moving]
            if others:
                problems.append('%s: stem %s already used by %s' % (r['new'], stem(r['new']), ', '.join(others)))
    return problems


def build_pattern(rows):
    """One regex for every row: full path, bare file name, bare stem (not for symbol-like stems)."""
    repl = {}
    for r in rows:
        old, new = r['old'], r['new']
        repl[old] = new
        repl[Path(old).name] = Path(new).name
        if not SYMBOL_STEM.match(stem(old)):
            repl[stem(old)] = stem(new)
    keys = sorted(repl, key=len, reverse=True)
    alts = []
    for k in keys:
        if '/' in k:
            alts.append(r'(?<![\w$.-])' + re.escape(k) + RIGHT)
        else:
            alts.append(LEFT + re.escape(k) + RIGHT)
    return re.compile('|'.join(alts)), repl


def candidate_files():
    names = [n for n in git('ls-files', '-z').split('\0') if n]
    out = []
    for n in names:
        if n in EXCLUDE_FILES or n.startswith(EXCLUDE_DIRS) or n == PLAN.relative_to(ROOT).as_posix():
            continue
        if Path(n).suffix.lower() not in TEXT_EXT and Path(n).name not in ('README', '.gitignore'):
            continue
        out.append(n)
    return out


def split_generated(text):
    """(before, generated block, after) of docs/CODE_MAP.md; the block is never rewritten by the regex."""
    i = text.find(BEGIN)
    j = text.find(END)
    if i < 0 or j < i:
        return text, None, ''
    return text[:i], text[i:j + len(END)], text[j + len(END):]


def replace_text(text, pattern, repl, hits, rel):
    def sub(m):
        hits.append((rel, m.group(0), repl[m.group(0)]))
        return repl[m.group(0)]
    return pattern.sub(sub, text)


def renamed_table(rows, newline):
    lines = [BEGIN, '', '| Old file | New file |', '|---|---|']
    for r in rows:
        lines.append('| `%s` | `%s` |' % (r['old'], r['new']))
    lines += ['', END]
    return newline.join(lines)


def update_code_map(rows, dry):
    """Rewrite the generated table (old -> new) inside the "Renamed files" section of docs/CODE_MAP.md."""
    data = CODE_MAP.read_bytes()
    text = data.decode('utf-8')
    nl = '\r\n' if '\r\n' in text else '\n'
    table = renamed_table(rows, nl)
    before, block, after = split_generated(text)
    if block is None:
        intro = nl.join(['', '## Renamed files', '',
                         'Source files renamed so their names say what they hold. VAs and symbols did not change. '
                         'The full list with reasons is `config/US/file_renames.tsv`; `tools/port_rename_notes.py` '
                         'updates notes that still use the old names.', '', ''])
        new = text.rstrip('\r\n') + nl + intro + table + nl
    else:
        new = before + table + after
    if new != text and not dry:
        CODE_MAP.write_bytes(new.encode('utf-8'))
    return new != text


def apply(rows, dry=False, package=True, verbose=False):
    problems = check(rows)
    if problems:
        raise SystemExit('rename_file: refused:\n  ' + '\n  '.join(problems))
    todo = [r for r in rows if r['state'] == 'todo']
    print('%d rows: %d to move, %d already applied' % (len(rows), len(todo), len(rows) - len(todo)))
    for r in todo:
        print('  git mv %s %s' % (r['old'], r['new']))
        if not dry:
            git('mv', r['old'], r['new'])
    pattern, repl = build_pattern(rows)
    hits, changed, rehash = [], [], {}
    for rel in candidate_files():
        path = ROOT / rel
        if not path.is_file():
            continue
        data = path.read_bytes()
        try:
            text = data.decode('utf-8')
        except UnicodeDecodeError:
            continue
        if rel == 'docs/CODE_MAP.md':
            before, block, after = split_generated(text)
            new = replace_text(before, pattern, repl, hits, rel) + (block or '') + replace_text(after, pattern, repl, hits, rel)
        else:
            new = replace_text(text, pattern, repl, hits, rel)
        if new != text:
            out = new.encode('utf-8')
            changed.append(rel)
            if rel.startswith('src/'):
                rehash[sha(data)] = sha(out)
            if not dry:
                path.write_bytes(out)
    by_file = {}
    for rel, old, new in hits:
        by_file.setdefault(rel, []).append((old, new))
    for rel in changed:
        print('  edit %s (%d)' % (rel, len(by_file.get(rel, []))))
        if verbose:
            for old, new in sorted(set(by_file[rel])):
                print('      %s -> %s' % (old, new))
    # source_sha256 of compiled units whose comments / #include lines changed
    if rehash and not dry:
        for p in HASHED:
            text = p.read_bytes().decode('utf-8')
            new = re.sub(r'"source_sha256": "([0-9a-f]{64})"',
                         lambda m: '"source_sha256": "%s"' % rehash.get(m.group(1), m.group(1)), text)
            if new != text:
                p.write_bytes(new.encode('utf-8'))
                print('  rehash %s' % p.relative_to(ROOT).as_posix())
    if update_code_map(rows, dry):
        print('  table docs/CODE_MAP.md (Renamed files)')
    print('%d files edited, %d references%s' % (len(changed), len(hits), ' (dry run, nothing written)' if dry else ''))
    if package and not dry:
        subprocess.run([sys.executable, '-B', str(ROOT / 'tools/make_package.py')], cwd=ROOT, check=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('old', nargs='?', help='one file to rename (with NEW)')
    ap.add_argument('new', nargs='?')
    ap.add_argument('--reason', default='', help='with OLD NEW: reason column of the plan row')
    ap.add_argument('--plan', type=Path, default=PLAN)
    ap.add_argument('--dry-run', action='store_true')
    ap.add_argument('--verbose', action='store_true', help='list every replaced name per file')
    ap.add_argument('--no-package', action='store_true', help='do not regenerate PACKAGE.json')
    a = ap.parse_args()
    rows = read_plan(a.plan) if a.plan.is_file() else []
    if a.old:
        if not a.new:
            ap.error('OLD needs NEW')
        if any(r['old'] == a.old for r in rows):
            raise SystemExit('rename_file: %s is already in %s' % (a.old, a.plan))
        rows.append(dict(old=a.old, new=a.new, reason=a.reason))
        problems = check(rows)
        if problems:
            raise SystemExit('rename_file: refused:\n  ' + '\n  '.join(problems))
        if not a.dry_run:
            data = a.plan.read_bytes() if a.plan.is_file() else b'old_path\tnew_path\treason\n'
            if not data.endswith(b'\n'):
                data += b'\n'
            a.plan.write_bytes(data + ('%s\t%s\t%s\n' % (a.old, a.new, a.reason)).encode('utf-8'))
    if not rows:
        raise SystemExit('rename_file: nothing to do (%s is empty)' % a.plan)
    apply(rows, a.dry_run, not a.no_package, a.verbose)


if __name__ == '__main__':
    main()
